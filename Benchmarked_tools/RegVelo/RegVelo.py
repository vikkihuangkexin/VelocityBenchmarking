#!/usr/bin/env python3
"""
RegVelo RNA velocity pipeline for VelocityBenchmarking (real data).

RegVelo extends veloVI with a gene regulatory network (GRN) prior. For real data
the prior is computed with pySCENIC (grn -> ctx -> aucell) and converted into a
0/1 regulator-target matrix; this script consumes either that pre-computed GRN
(``--grn-parquet``) or the pySCENIC AUCell loom (``--pyscenic-loom``) from which
the GRN is derived.

Installation:
    pip install regvelo scanpy scvelo GPUtil pynvml psutil pandas numpy scikit-learn
    pip install loompy pyarrow
    # A GPU-enabled PyTorch build is installed automatically as a dependency of regvelo.

Usage:
    # GRN parquet already generated by pySCENIC
    python RegVelo.py --input data.h5ad --output-dir ./output --cluster-key celltype \
        --grn-parquet regulon_mat_processed_all_regulons.parquet

    # Generate the GRN parquet from the pySCENIC AUCell loom, then run RegVelo
    python RegVelo.py --input data.h5ad --output-dir ./output --cluster-key celltype \
        --pyscenic-loom pyscenic_output.loom

    python RegVelo.py --metadata-file datasets.csv --output-dir ./output

Note:
    Simulated-data processing uses an a-priori GRN instead of pySCENIC and is kept
    in the separate RegVelo_sim.py script.
"""

