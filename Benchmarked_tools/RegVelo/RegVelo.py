def detect_species(filename: str) -> str:
    """Detect the species token (``mm`` / ``hs``) from a file name."""
    tokens = filename.replace(".", "_").split("_")
    for token in tokens:
        lowered = token.lower()
        if lowered == "mm":
            return "mm"
        if lowered == "hs":
            return "hs"
        if lowered == "peripheral":
            return "hs"
    raise ValueError(f"Could not detect species from '{filename}' (expected 'Mm' or 'Hs')")


def convert_h5ad_to_loom(data_path, save_dir, data_file) -> Path:
    """Convert an h5ad file into the loom format consumed by pySCENIC."""
    import loompy  # noqa: F401 - imported for a clear error if missing

    adata = sc.read(data_path, cache=False)
    species = detect_species(data_file)

    adata_loom = sc.AnnData(adata.X, obs=adata.obs.copy(), var=adata.var.copy())
    adata_loom.var["Gene"] = adata_loom.var_names
    adata_loom.obs["CellID"] = adata_loom.obs_names

    save_dir = Path(save_dir)
    save_dir.mkdir(parents=True, exist_ok=True)
    loom_path = save_dir / "adata.loom"
    adata_loom.write_loom(str(loom_path))
    (save_dir / "species.txt").write_text(species, encoding="utf-8")
    print(f"[INFO] loom written: {loom_path} (species={species})")
    return loom_path


def generate_grn_parquet(pyscenic_loom, parquet_out=None) -> Path:
    """Build the RegVelo GRN parquet from a pySCENIC AUCell output loom.

    Extracts the regulon-target matrix, binarizes it and writes a square 0/1
    ``genes x genes`` matrix. TF names are recovered from the regulon labels
    (e.g. ``"Sox10(+)"``) and duplicate regulons of the same TF are merged.
    """
    import loompy as lp

    pyscenic_loom = Path(pyscenic_loom)
    if parquet_out is None:
        parquet_out = pyscenic_loom.parent / "regulon_mat_processed_all_regulons.parquet"
    parquet_out = Path(parquet_out)

    if parquet_out.exists():
        print(f"[INFO] GRN parquet already exists: {parquet_out}")
        return parquet_out
    if not pyscenic_loom.exists():
        raise FileNotFoundError(f"pySCENIC AUCell loom not found: {pyscenic_loom}")

    csv_out = pyscenic_loom.parent / "regulon_mat_all_regulons.csv"

    lf = lp.connect(str(pyscenic_loom), mode="r+", validate=False)
    regulons = lf.ra.Regulons
    res = pd.concat(
        [pd.Series(r.tolist(), index=regulons.dtype.names) for r in regulons], axis=1
    )
    gene_names = lf.ra.Gene
    if gene_names.dtype.kind == "S":
        gene_names = np.array([g.decode("utf-8") for g in gene_names])
    res.columns = gene_names
    res.to_csv(csv_out)
    lf.close()
    print(f"[INFO] regulon matrix: {res.shape[0]} regulons x {res.shape[1]} genes")

    reg = pd.read_csv(csv_out, index_col=0)
    reg.index = reg.index.str.extract(r"(\w+)")[0]
    reg = reg.groupby(reg.index).sum()
    reg[reg != 0] = 1

    tfs = np.unique(reg.index.tolist())
    genes = np.unique(tfs.tolist() + reg.columns.tolist())
    grn = pd.DataFrame(0, index=genes, columns=genes)
    grn.loc[tfs, reg.columns.tolist()] = np.array(reg)

    mask = (grn.sum(0) != 0) | (grn.sum(1) != 0)
    grn = grn.loc[mask, mask].copy()
    grn.to_parquet(parquet_out)
    print(f"[INFO] GRN parquet: {parquet_out} ({grn.shape[0]} x {grn.shape[1]})")
    return parquet_out


def load_grn(grn_parquet=None, pyscenic_loom=None) -> pd.DataFrame:
    """Load the prior GRN matrix from a parquet file or a pySCENIC loom."""
    if grn_parquet is None:
        if pyscenic_loom is None:
            raise ValueError("Provide either --grn-parquet or --pyscenic-loom")
        grn_parquet = generate_grn_parquet(pyscenic_loom)
    grn = pd.read_parquet(grn_parquet)
    print(f"[INFO] prior GRN loaded from {grn_parquet}: {grn.shape}")
    return grn


