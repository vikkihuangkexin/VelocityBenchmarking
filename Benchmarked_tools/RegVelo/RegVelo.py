def resolve_n_top_genes(n_vars: int, n_top_genes: int = DEFAULT_N_TOP_GENES) -> int:
    """Lower ``n_top_genes`` when the dataset has fewer genes (avoids IndexError)."""
    n_vars = int(n_vars)
    n_top_genes = int(n_top_genes)
    if n_vars >= n_top_genes:
        return n_top_genes
    new = ((n_vars - 1) // 100) * 100
    if new < 100:
        new = n_vars - 1
    new = max(1, int(new))
    print(f"[NTOP] {n_vars} genes < {n_top_genes}; using n_top_genes={new}")
    return new


def min_max_scale_layers(adata, layers: Sequence[str] = ("Ms", "Mu")) -> str:
    """Min-max scale the given layers (fallback when filter_genes is skipped)."""
    from sklearn.preprocessing import MinMaxScaler

    status = []
    for layer in layers:
        if layer not in adata.layers:
            status.append(f"{layer}:missing")
            continue
        arr = adata.layers[layer]
        if hasattr(arr, "toarray"):
            arr = arr.toarray()
        arr = np.asarray(arr)
        if arr.ndim != 2 or arr.shape[1] == 0:
            status.append(f"{layer}:skipped(no features)")
            continue
        adata.layers[layer] = MinMaxScaler().fit_transform(arr)
        status.append(f"{layer}:ok")
    return ", ".join(status)


def preprocess_adata(
    adata,
    grn: pd.DataFrame,
    cluster_key: str,
    n_top_genes: int = DEFAULT_N_TOP_GENES,
    n_pcs: int = 30,
    n_neighbors: int = 50,
    issue_log: Optional[str] = None,
    dataset_label: str = "",
):
    """Normalized RegVelo preprocessing (pySCENIC GRN prior + gene selection)."""
    api = load_regvelo_api()
    rgv = api["rgv"]

    if cluster_key != "clusters" and cluster_key in adata.obs.columns:
        adata.obs["clusters"] = adata.obs[cluster_key]

    scv.pp.filter_and_normalize(adata, min_shared_counts=20)
    n_top_genes = resolve_n_top_genes(adata.n_vars, n_top_genes)
    sc.pp.filter_genes_dispersion(adata, n_top_genes=n_top_genes)
    sc.pp.log1p(adata)
    if "neighbors" not in adata.uns:
        sc.pp.neighbors(adata, n_pcs=n_pcs, n_neighbors=n_neighbors)
    scv.pp.moments(adata, n_pcs=None, n_neighbors=None)

    # Inject the pySCENIC prior GRN (rows = targets, columns = regulators).
    adata = rgv.pp.set_prior_grn(adata, grn.T)

    velocity_genes = rgv.pp.preprocess_data(adata.copy()).var_names.tolist()
    tf_mask = adata.var_names[adata.uns["skeleton"].sum(1) != 0]
    var_mask = np.union1d(tf_mask, velocity_genes)
    adata = adata[:, var_mask].copy()
    adata.uns["skeleton"] = adata.uns["skeleton"].loc[
        adata.var_names.tolist(), adata.var_names.tolist()
    ]

    # rgv.pp.filter_genes can drop every gene when the prior GRN is too sparse;
    # fall back to the pre-filter gene set (min-max scaled only) in that case.
    adata_before = adata.copy()
    skeleton_before = adata.uns["skeleton"].copy()
    skipped = False
    issue_error = None
    try:
        adata = rgv.pp.filter_genes(adata)
        adata = rgv.pp.preprocess_data(adata, filter_on_r2=False)
    except Exception as exc:  # noqa: BLE001 - deliberate fallback
        skipped = True
        issue_error = exc
        adata = adata_before
        adata.uns["skeleton"] = skeleton_before
        adata.uns["network"] = skeleton_before.copy()
        adata.uns["regulators"] = adata.var_names.to_numpy()
        adata.uns["targets"] = adata.var_names.to_numpy()
        scale_status = min_max_scale_layers(adata)
        print(f"[WARN] filter_genes skipped ({exc}); min-max: {scale_status}")

    adata.var["velocity_genes"] = adata.var_names.isin(velocity_genes)
    adata.var["TF"] = adata.var_names.isin(tf_mask)

    if skipped and issue_log:
        _log_issue(issue_log, dataset_label, issue_error)

    return adata


def _log_issue(issue_log: str, dataset_label: str, error: Exception) -> None:
    try:
        Path(issue_log).parent.mkdir(parents=True, exist_ok=True)
        with open(issue_log, "a", encoding="utf-8") as handle:
            handle.write("=" * 60 + "\n")
            handle.write(f"dataset: {dataset_label}\n")
            handle.write(f"error: {type(error).__name__}: {error}\n")
            handle.write(traceback.format_exc() + "\n")
    except Exception as exc:  # noqa: BLE001
        print(f"[WARN] could not write issue log: {exc}")


