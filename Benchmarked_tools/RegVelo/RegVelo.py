def seed_everything(seed: int) -> None:
    import random

    random.seed(seed)
    np.random.seed(seed)
    try:
        import torch

        torch.manual_seed(seed)
        if torch.cuda.is_available():
            torch.cuda.manual_seed_all(seed)
    except Exception:
        pass


def pick_free_gpu() -> int:
    """Return the physical GPU index with the most free memory (fallback: 0)."""
    try:
        out = subprocess.check_output(
            ["nvidia-smi", "--query-gpu=index,memory.free", "--format=csv,noheader,nounits"],
            universal_newlines=True,
        )
        best_idx, best_free = 0, -1
        for line in out.strip().splitlines():
            parts = [part.strip() for part in line.split(",")]
            if len(parts) < 2:
                continue
            free = int(parts[1])
            if free > best_free:
                best_free = free
                best_idx = int(parts[0])
        return best_idx
    except Exception as exc:  # noqa: BLE001 - fall back to device 0
        print(f"[device] nvidia-smi query failed, using GPU 0: {exc}", file=sys.stderr)
        return 0


def configure_cuda(cuda: Optional[int]) -> Optional[str]:
    """Expose ``--cuda`` through ``CUDA_VISIBLE_DEVICES`` (never overrides the caller)."""
    if "CUDA_VISIBLE_DEVICES" in os.environ:
        return os.environ["CUDA_VISIBLE_DEVICES"]
    if cuda is None:
        cuda = pick_free_gpu()
    os.environ.setdefault("CUDA_VISIBLE_DEVICES", str(cuda))
    return os.environ.get("CUDA_VISIBLE_DEVICES")


def load_regvelo_api():
    """Import regvelo / torch lazily (after CUDA environment setup)."""
    if not _REGVELO_API:
        import torch
        import regvelo as rgv
        from regvelo import REGVELOVI

        _REGVELO_API.update(torch=torch, rgv=rgv, REGVELOVI=REGVELOVI)
    return _REGVELO_API


def cleanup_resources() -> None:
    gc.collect()
    plt.close("all")


